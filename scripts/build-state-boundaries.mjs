/**
 * Build the offline state-boundary table the app uses to turn a GPS fix into a
 * USPS state code.
 *
 * Fred cannot call Location.reverseGeocodeAsync for this. On Android that goes
 * through the platform Geocoder, which needs network — so it would fail in the
 * exact situation Fred exists for. State resolution has to be local data plus
 * point-in-polygon, and small enough to sit in the bundle.
 *
 * Source: the Census-derived low-resolution us-states.json published by
 * PublicaMundi (US Census TIGER/Line cartographic boundaries, public domain).
 * It is coarse — a few hundred metres of slop along a border — which is fine
 * for picking a flora-and-fauna pack and is recorded in docs/licensing.md.
 *
 *   node scripts/build-state-boundaries.mjs <input.json> <output.ts>
 */
import { readFileSync, writeFileSync } from 'node:fs';

/** Full name -> USPS code. The source carries names and FIPS ids, not codes. */
const USPS = {
  Alabama: 'AL', Alaska: 'AK', Arizona: 'AZ', Arkansas: 'AR', California: 'CA',
  Colorado: 'CO', Connecticut: 'CT', Delaware: 'DE', 'District of Columbia': 'DC',
  Florida: 'FL', Georgia: 'GA', Hawaii: 'HI', Idaho: 'ID', Illinois: 'IL',
  Indiana: 'IN', Iowa: 'IA', Kansas: 'KS', Kentucky: 'KY', Louisiana: 'LA',
  Maine: 'ME', Maryland: 'MD', Massachusetts: 'MA', Michigan: 'MI',
  Minnesota: 'MN', Mississippi: 'MS', Missouri: 'MO', Montana: 'MT',
  Nebraska: 'NE', Nevada: 'NV', 'New Hampshire': 'NH', 'New Jersey': 'NJ',
  'New Mexico': 'NM', 'New York': 'NY', 'North Carolina': 'NC',
  'North Dakota': 'ND', Ohio: 'OH', Oklahoma: 'OK', Oregon: 'OR',
  Pennsylvania: 'PA', 'Rhode Island': 'RI', 'South Carolina': 'SC',
  'South Dakota': 'SD', Tennessee: 'TN', Texas: 'TX', Utah: 'UT',
  Vermont: 'VT', Virginia: 'VA', Washington: 'WA', 'West Virginia': 'WV',
  Wisconsin: 'WI', Wyoming: 'WY', 'Puerto Rico': 'PR',
};

/** ~11 m at the equator, finer than the source data's own resolution. */
const PRECISION = 4;
const round = (n) => Number(n.toFixed(PRECISION));

/** GeoJSON gives [lon, lat] pairs; flatten them — it halves the JSON. */
function flatten(ring) {
  const out = [];
  for (const [lon, lat] of ring) out.push(round(lon), round(lat));
  return out;
}

/** Outer rings only. State holes (none here) would need a second pass. */
function ringsOf(geometry) {
  return geometry.type === 'Polygon'
    ? [geometry.coordinates[0]]
    : geometry.coordinates.map((poly) => poly[0]);
}

const [, , inPath, outPath] = process.argv;
if (!inPath || !outPath) {
  console.error('usage: node scripts/build-state-boundaries.mjs <input.json> <output.ts>');
  process.exit(1);
}

const src = JSON.parse(readFileSync(inPath, 'utf8'));
const table = {};
let dropped = 0;

for (const feature of src.features) {
  const code = USPS[feature.properties.name];
  if (code === undefined) {
    dropped += 1;
    console.warn(`skipped unmapped region: ${feature.properties.name}`);
    continue;
  }
  const rings = ringsOf(feature.geometry).map(flatten);
  let minLon = Infinity, minLat = Infinity, maxLon = -Infinity, maxLat = -Infinity;
  for (const ring of rings) {
    for (let i = 0; i < ring.length; i += 2) {
      if (ring[i] < minLon) minLon = ring[i];
      if (ring[i] > maxLon) maxLon = ring[i];
      if (ring[i + 1] < minLat) minLat = ring[i + 1];
      if (ring[i + 1] > maxLat) maxLat = ring[i + 1];
    }
  }
  // The bbox is a cheap reject: most lookups fail it and never walk a ring.
  table[code] = { bbox: [minLon, minLat, maxLon, maxLat], rings };
}

const header = `// Generated by scripts/build-state-boundaries.mjs — do not edit by hand.
// Source: US Census TIGER/Line cartographic boundaries (public domain), via the
// low-resolution us-states.json published by PublicaMundi. See docs/licensing.md.
import type { StateBoundaries } from './index.ts';

export const STATE_BOUNDARIES: StateBoundaries = `;
writeFileSync(outPath, `${header}${JSON.stringify(table)};\n`);
const vertices = Object.values(table).reduce(
  (n, s) => n + s.rings.reduce((m, r) => m + r.length / 2, 0), 0);
console.log(
  `${Object.keys(table).length} regions, ${vertices} vertices, ` +
  `${(readFileSync(outPath).length / 1024).toFixed(1)} KB` +
  (dropped > 0 ? `, ${dropped} dropped` : ''));

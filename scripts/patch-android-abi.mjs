/**
 * Build for arm64-v8a only.
 *
 * The default builds four architectures and ships them all in one APK. Measured
 * on this project: arm64-v8a 131 MB, x86_64 88 MB, x86 66 MB, armeabi-v7a
 * 41 MB. Only arm64-v8a runs on any current phone — x86 and x86_64 are
 * emulator targets and armeabi-v7a is 32-bit hardware from around 2015 — so
 * 195 MB of a 350 MB APK is weight no real device uses.
 *
 * This is not only tidiness. Installing over the USB/IP link to WSL stalls on
 * large files and needs chunked transfers with retries, so halving the APK
 * makes every install of every future build materially less painful.
 *
 * **This drops emulator support.** Anyone needing an x86_64 emulator should
 * build with `-PreactNativeArchitectures=arm64-v8a,x86_64`, which overrides
 * this without editing anything. RC-KR1 wants a store build, and Play accepts
 * per-architecture splits, so this is the right default to grow from rather
 * than something to undo.
 *
 * android/ is gitignored and regenerated by prebuild, so this is a tracked
 * script following patch-onnx-gradle.mjs. Idempotent.
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';

const FILE = new URL('../apps/mobile/android/gradle.properties', import.meta.url);
const NEEDLE = 'reactNativeArchitectures=armeabi-v7a,arm64-v8a,x86,x86_64';
const MARK = '# Patched: arm64 only. See scripts/patch-android-abi.mjs';
const REPLACEMENT = `${MARK}\nreactNativeArchitectures=arm64-v8a`;

if (!existsSync(FILE)) {
  console.log('[patch-android-abi] android/ not generated; nothing to do');
  process.exit(0);
}
const src = readFileSync(FILE, 'utf8');
if (src.includes(MARK)) {
  console.log('[patch-android-abi] already patched');
  process.exit(0);
}
if (!src.includes(NEEDLE)) {
  console.error('[patch-android-abi] architecture line not found; refusing to guess');
  process.exit(1);
}
writeFileSync(FILE, src.replace(NEEDLE, REPLACEMENT), 'utf8');
console.log('[patch-android-abi] building arm64-v8a only');

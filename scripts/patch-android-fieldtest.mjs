/**
 * Let a release build be made debuggable for field tests, and only on request.
 *
 * Field tests need a standalone build (a debug build fetches its JS from a
 * Metro dev server) that `adb run-as` can still read: the drive-test track CSV,
 * staged packs and the devhooks inbox all live in the app's private storage.
 * run-as refuses on a non-debuggable package.
 *
 * This used to set `debuggable true` on every release build, which made every
 * APK unshippable (#30). Now the release type reads a Gradle property:
 *
 *   ./gradlew assembleRelease                        # not debuggable: shippable
 *   ./gradlew assembleRelease -Pfred.fieldTest=true  # debuggable: field tests
 *
 * tools/eval/build-apk.sh wraps both and checks the result in the built APK.
 *
 * android/ is gitignored and regenerated by `expo prebuild`, which is why this
 * is a tracked script rather than an edit in place, following
 * patch-onnx-gradle.mjs. Idempotent, and it migrates a file carrying the old
 * unconditional patch.
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';

const FILE = new URL('../apps/mobile/android/app/build.gradle', import.meta.url);
const NEEDLE = `        release {
            // Caution! In production, you need to generate your own keystore file.`;
const MARK = '// Patched: debuggable only with -Pfred.fieldTest=true. See scripts/patch-android-fieldtest.mjs';
const REPLACEMENT = `        release {
            ${MARK}
            debuggable((findProperty('fred.fieldTest') ?: 'false').toBoolean())
            // Caution! In production, you need to generate your own keystore file.`;
// What earlier versions of this script inserted: debuggable unconditionally.
const OLD = `            // Patched: field-test builds stay debuggable. See scripts/patch-android-fieldtest.mjs
            debuggable true
`;

if (!existsSync(FILE)) {
  console.log('[patch-android-fieldtest] android/ not generated; nothing to do');
  process.exit(0);
}
let src = readFileSync(FILE, 'utf8');
if (src.includes(OLD)) {
  src = src.replace(OLD, '');
  console.log('[patch-android-fieldtest] removed the old unconditional debuggable patch');
}
if (src.includes(MARK)) {
  writeFileSync(FILE, src, 'utf8');
  console.log('[patch-android-fieldtest] already patched');
  process.exit(0);
}
if (!src.includes(NEEDLE)) {
  console.error('[patch-android-fieldtest] release block not found; refusing to guess');
  process.exit(1);
}
writeFileSync(FILE, src.replace(NEEDLE, REPLACEMENT), 'utf8');
console.log('[patch-android-fieldtest] release builds are debuggable only with -Pfred.fieldTest=true');

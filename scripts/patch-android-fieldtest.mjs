/**
 * Make the release build debuggable, so a field test can be retrieved.
 *
 * B-KR1/2/3 are verified by driving, which means the app has to run without a
 * laptop — a debug build fetches its JS from a Metro dev server, so it cannot.
 * That points at `assembleRelease`, which embeds the bundle.
 *
 * But a release APK is not debuggable, and `adb run-as` refuses on a
 * non-debuggable package. That is the only way to read the track CSV the
 * recorder writes into the app's documents directory, because expo-file-system
 * on Android exposes `cache`, `bundle` and `document` and no external path.
 * So a plain release build produces the data and then hides it.
 *
 * Setting `debuggable true` on the release type gives the one build that is
 * both standalone and readable. It is a field-test artefact, not a shippable
 * one — RC-KR1 wants a proper store build, and this flag must come off first.
 *
 * android/ is gitignored and regenerated by `expo prebuild`, which is why this
 * is a tracked script rather than an edit in place, following
 * patch-onnx-gradle.mjs. Idempotent.
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';

const FILE = new URL('../apps/mobile/android/app/build.gradle', import.meta.url);
const NEEDLE = `        release {
            // Caution! In production, you need to generate your own keystore file.`;
const MARK = '// Patched: field-test builds stay debuggable. See scripts/patch-android-fieldtest.mjs';
const REPLACEMENT = `        release {
            ${MARK}
            debuggable true
            // Caution! In production, you need to generate your own keystore file.`;

if (!existsSync(FILE)) {
  console.log('[patch-android-fieldtest] android/ not generated; nothing to do');
  process.exit(0);
}
const src = readFileSync(FILE, 'utf8');
if (src.includes(MARK)) {
  console.log('[patch-android-fieldtest] already patched');
  process.exit(0);
}
if (!src.includes(NEEDLE)) {
  console.error('[patch-android-fieldtest] release block not found; refusing to guess');
  process.exit(1);
}
writeFileSync(FILE, src.replace(NEEDLE, REPLACEMENT), 'utf8');
console.log('[patch-android-fieldtest] release builds are now debuggable');

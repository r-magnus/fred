/**
 * Sign release builds with Fred's own key (#29), not Android's shared debug key.
 *
 * An app update installs only over one signed with the same key, so testers'
 * copies can be updated without losing their downloads only while every
 * release is signed with this one key. The key and its passwords never enter
 * the repo: Gradle reads them from ~/.gradle/gradle.properties,
 *
 *   FRED_RELEASE_STORE_FILE=/home/.../.fred-signing/fred-release.p12
 *   FRED_RELEASE_STORE_PASSWORD=...
 *   FRED_RELEASE_KEY_ALIAS=fred
 *   FRED_RELEASE_KEY_PASSWORD=...
 *
 * Without them a release build falls back to the debug key, as before, and
 * tools/eval/build-apk.sh refuses to call the result shippable.
 *
 * android/ is gitignored and regenerated by `expo prebuild`, so this is a
 * tracked script, like patch-android-fieldtest.mjs. Idempotent.
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';

const FILE = new URL('../apps/mobile/android/app/build.gradle', import.meta.url);
const MARK = '// Patched: Fred release key when configured. See scripts/patch-android-signing.mjs';
const CONFIG_NEEDLE = `    signingConfigs {
        debug {`;
const CONFIG = `    signingConfigs {
        ${MARK}
        if (findProperty('FRED_RELEASE_STORE_FILE')) {
            release {
                storeFile file(findProperty('FRED_RELEASE_STORE_FILE'))
                storePassword findProperty('FRED_RELEASE_STORE_PASSWORD')
                keyAlias findProperty('FRED_RELEASE_KEY_ALIAS')
                keyPassword findProperty('FRED_RELEASE_KEY_PASSWORD')
            }
        }
        debug {`;
const USE_NEEDLE = `            // see https://reactnative.dev/docs/signed-apk-android.
            signingConfig signingConfigs.debug`;
const USE = `            // see https://reactnative.dev/docs/signed-apk-android.
            signingConfig findProperty('FRED_RELEASE_STORE_FILE') ? signingConfigs.release : signingConfigs.debug`;

if (!existsSync(FILE)) {
  console.log('[patch-android-signing] android/ not generated; nothing to do');
  process.exit(0);
}
const src = readFileSync(FILE, 'utf8');
if (src.includes(MARK)) {
  console.log('[patch-android-signing] already patched');
  process.exit(0);
}
if (!src.includes(CONFIG_NEEDLE) || !src.includes(USE_NEEDLE)) {
  console.error('[patch-android-signing] signing blocks not found; refusing to guess');
  process.exit(1);
}
writeFileSync(FILE, src.replace(CONFIG_NEEDLE, CONFIG).replace(USE_NEEDLE, USE), 'utf8');
console.log('[patch-android-signing] release builds use the Fred key when ~/.gradle/gradle.properties has it');
